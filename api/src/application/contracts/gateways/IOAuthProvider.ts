import type { AuthIdentity } from '#application/entities/AuthIdentity';

export interface IOAuthProfile {
  /** The provider's `sub` claim. */
  providerUserId: string;
  email: string | null;
  emailVerified: boolean;
  name: string | null;
}

/**
 * Implementations validate the id_token (JWKS signature, iss, aud, exp, nonce)
 * and throw OAuthFailed when it is not acceptable.
 */
export interface IOAuthProvider {
  readonly name: AuthIdentity.Provider;
  /** Apple answers with response_mode=form_post: a cross-site POST that only carries SameSite=None cookies. */
  readonly usesFormPost: boolean;
  getAuthorizationUrl(input: IOAuthProvider.AuthorizationUrlInput): URL;
  exchangeCode(input: IOAuthProvider.ExchangeCodeInput): Promise<IOAuthProfile>;
  /** Native (mobile) sign-in. `nonce` is the raw nonce generated by the app. */
  verifyIdToken(input: IOAuthProvider.VerifyIdTokenInput): Promise<IOAuthProfile>;
}

export namespace IOAuthProvider {
  export type AuthorizationUrlInput = {
    state: string;
    codeChallenge: string;
    nonce: string;
    redirectUri: string;
  };

  export type ExchangeCodeInput = {
    code: string;
    codeVerifier: string;
    nonce: string;
    redirectUri: string;
  };

  export type VerifyIdTokenInput = {
    idToken: string;
    nonce?: string;
  };
}
